function lookup(ns: TranslationNamespace, locale: Locale, key: string): string | undefined {
  return translations[ns]?.[locale]?.[key];
}

export function t(
  ns: TranslationNamespace,
  key: string,
  params?: Record<string, string | number>,
): string {
  const locale = DEFAULT_LOCALE;
  let text = lookup(ns, locale, key) ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      text = text.replace(new RegExp(`{{${k}}}`, "g"), String(v));
    }
  }
  return text;
}

export function useTranslation(locale: Locale = DEFAULT_LOCALE) {
  function tx(
    ns: TranslationNamespace,
    key: string,
    params?: Record<string, string | number>,
  ): string {
    let text = lookup(ns, locale, key) ?? lookup(ns, DEFAULT_LOCALE, key) ?? key;
    if (params) {
      for (const [k, v] of Object.entries(params)) {
        text = text.replace(new RegExp(`{{${k}}}`, "g"), String(v));
      }
    }
    // visibly mark incomplete translations so nothing wrong is silently shown
    if (
      text.includes("incomplete") ||
      text.includes("marker") ||
      text.includes("_kn") ||
      text.includes("fibonacci") ||
      text.includes("kshetra") ||
      text.includes("nImage") ||
      text.includes("nameno")
    ) {
      return `[${locale.toUpperCase()}] ${key}`;
    }
    return text;
  }
  return { t: tx, locale };
}

